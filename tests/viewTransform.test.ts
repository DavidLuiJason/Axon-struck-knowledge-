import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fitScale, fitView, maxViewScale, clampScale, clampView, zoomAt, panBy, stageToPicture, pictureToStage, refitKeepingCentre, type ViewSize } from '../src/tools/imageEdit/viewTransform.ts';
let checks = 0;
function check(condition: unknown, message: string): asserts condition { checks++; assert.ok(condition, message); }
function near(a: number, b: number, epsilon = 1e-7) { check(Math.abs(a - b) <= epsilon, `expected ${a} ≈ ${b}`); }
const stage = { width: 360, height: 640 };
for (const picture of [{ width: 1600, height: 900 }, { width: 900, height: 1600 }, { width: 1, height: 1 }, { width: 100000, height: 200000 }]) {
  const f = fitScale(stage, picture); check(f.ok, 'fit scale should succeed');
  near(f.value, Math.min(stage.width / picture.width, stage.height / picture.height));
  const v = fitView(stage, picture); check(v.ok, 'fit should succeed');
  near(v.value.scale, 1);
  const fw = picture.width * f.value, fh = picture.height * f.value;
  check(fw <= stage.width + 1e-7 && fh <= stage.height + 1e-7, 'fit must fit both dimensions');
  near(v.value.tx, (stage.width - fw) / 2); near(v.value.ty, (stage.height - fh) / 2);
  const resized = refitKeepingCentre(v.value, stage, picture, { width: 640, height: 360 }, picture);
  check(resized.ok, 'refit should succeed');
  const oldCentrePicture = stageToPicture({ x: stage.width / 2, y: stage.height / 2 }, v.value, stage, picture);
  check(oldCentrePicture.ok, 'old stage centre converts to picture point');
  const newCentrePicture = stageToPicture({ x: 320, y: 180 }, resized.value, { width: 640, height: 360 }, picture);
  check(newCentrePicture.ok, 'new stage centre converts to picture point');
  near(oldCentrePicture.value.x, newCentrePicture.value.x); near(oldCentrePicture.value.y, newCentrePicture.value.y);
  const newFit = fitScale({ width: 640, height: 360 }, picture); check(newFit.ok, 'new fit');
  check(picture.width * newFit.value <= 640 + 1e-7 && picture.height * newFit.value <= 360 + 1e-7, 'refit dimensions fit');
}
const pic = { width: 1200, height: 800 };
const fit = fitView(stage, pic); check(fit.ok, 'initial fit');
const focal = { x: 150, y: 300 };
const before = stageToPicture(focal, fit.value, stage, pic); check(before.ok, 'inverse conversion before zoom');
const zoomed = zoomAt(fit.value, stage, pic, focal, 3); check(zoomed.ok, 'zoom succeeds');
const after = stageToPicture(focal, zoomed.value, stage, pic); check(after.ok, 'inverse conversion after zoom');
near(before.value.x, after.value.x); near(before.value.y, after.value.y);
const back = pictureToStage(before.value, zoomed.value, stage, pic); check(back.ok, 'forward conversion'); near(back.value.x, focal.x); near(back.value.y, focal.y);
const max = maxViewScale(stage, pic); check(max.ok, 'max scale');
const tooLarge = zoomAt(fit.value, stage, pic, focal, 1e8); check(tooLarge.ok, 'clamped huge zoom'); near(tooLarge.value.scale, max.value);
const tooSmall = clampScale(-5, max.value); check(tooSmall.ok, 'clamped low scale'); near(tooSmall.value, 1);
const largePan = panBy(zoomed.value, stage, pic, 1e8, -1e8); check(largePan.ok, 'pan clamped');
const fScale = fitScale(stage, pic);
const fScaleVal = fScale.ok ? fScale.value : 1;
const size = { width: pic.width * fScaleVal * largePan.value.scale, height: pic.height * fScaleVal * largePan.value.scale };
check(largePan.value.tx <= 1e-7 && largePan.value.ty <= 1e-7, 'large image top-left cannot move inside positive overflow');
check(largePan.value.tx >= stage.width - size.width - 1e-7 && largePan.value.ty >= stage.height - size.height - 1e-7, 'large image cannot leave right/bottom edges');
const smallPic = { width: 20, height: 10 };
const smallFit = fitView(stage, smallPic); check(smallFit.ok, 'tiny picture fit');
const smallPanned = panBy(smallFit.value, stage, smallPic, 200, -100); check(smallPanned.ok, 'small picture pan');
const sfScale = fitScale(stage, smallPic);
const sfScaleVal = sfScale.ok ? sfScale.value : 1;
near(smallPanned.value.tx, (stage.width - smallPic.width * sfScaleVal) / 2);
near(smallPanned.value.ty, (stage.height - smallPic.height * sfScaleVal) / 2);
check(!fitScale({ width: 0, height: 2 }, pic).ok, 'zero stage rejected');
check(!fitScale(stage, { width: Number.POSITIVE_INFINITY, height: 2 }).ok, 'infinite picture rejected');
check(!zoomAt(fit.value, stage, pic, focal, -1).ok, 'negative zoom rejected');
check(!zoomAt(fit.value, stage, pic, { x: NaN, y: 1 }, 2).ok, 'invalid focal rejected');
check(!clampScale(Number.NaN, 4).ok, 'NaN scale rejected');
check(!fitScale(null as unknown as ViewSize, pic).ok, 'null stage rejected without throwing');
check(!clampView(null as never, stage, pic).ok, 'null view rejected without throwing');
const editorSource = readFileSync(new URL('../src/components/editors/ImageEditorScreen.tsx', import.meta.url), 'utf8');
check((editorSource.match(/setBitmapVersion\(\(v\) => v \+ 1\)/g) ?? []).length === 4, 'R7 bitmapVersion increments remain at all four decode points');
check(editorSource.includes('[currentHistory.ops, updateCanvasDisplayBox, bitmapVersion]'), 'R7 bitmapVersion redraw dependency remains');
console.log(`viewTransform.test.ts: PASS (${checks} checks)`);
